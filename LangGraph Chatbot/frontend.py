import uuid

import streamlit as st
from langchain_core.messages import HumanMessage

from backend import chatbot

# ---------------- Page Config ----------------
st.set_page_config(
    page_title="LangGraph Chatbot",
    layout="wide",
)

# ============================================================
# STEP 2: Session State — generate a dynamic thread_id and
#         store it (along with history) in the session.
# ============================================================
# Messages of the currently active conversation
if "messages" not in st.session_state:
    st.session_state.messages = []  # list of {"role": ..., "content": ...}

# The active thread id (dynamic, per conversation)
if "thread_id" not in st.session_state:
    st.session_state.thread_id = str(uuid.uuid4())

# STEP 6: A list to store ALL thread ids created so far
if "thread_ids" not in st.session_state:
    st.session_state.thread_ids = [st.session_state.thread_id]

# Map of thread_id -> its message history (needed to reload a chat)
if "conversations" not in st.session_state:
    st.session_state.conversations = {st.session_state.thread_id: []}


def start_new_chat():
    """STEP 5: New Chat -> generate a new thread_id, save it in the
    session and reset the message history."""
    new_thread_id = str(uuid.uuid4())
    st.session_state.thread_id = new_thread_id
    st.session_state.thread_ids.append(new_thread_id)      # remember it
    st.session_state.conversations[new_thread_id] = []     # empty history
    st.session_state.messages = []                          # reset view


def load_conversation(thread_id):
    """STEP 9: Clicking a thread id loads that conversation."""
    st.session_state.thread_id = thread_id
    st.session_state.messages = st.session_state.conversations.get(thread_id, [])


def extract_model_name(message_chunk, metadata):
    """Pull the actual model name out of a streamed chunk.

    Different providers store it in different keys, so check the common
    ones in both the chunk's response_metadata and the stream metadata.
    """
    for source in (
        getattr(message_chunk, "response_metadata", None) or {},
        metadata or {},
    ):
        for key in ("model_name", "model", "ls_model_name"):
            value = source.get(key)
            if value:
                return value
    return None


# ============================================================
# STEP 1: Sidebar -> title + Start Chat button + "My Conversations"
# ============================================================
with st.sidebar:
    st.title(" LangGraph Chatbot")

    # Start Chat button (kicks off a fresh conversation)
    if st.button(" Start Chat", use_container_width=True):
        start_new_chat()
        st.rerun()

    st.markdown("###  My Conversations")

    # STEP 7 + 8: Load all thread ids in the sidebar as clickable buttons
    for tid in st.session_state.thread_ids:
        if st.button(f" Chat {tid[:8]}", key=tid, use_container_width=True):
            load_conversation(tid)
            st.rerun()

    # STEP 3: Display the current thread id in the sidebar
    st.markdown("---")
    st.caption("Current thread")
    st.code(st.session_state.thread_id, language=None)


# ============================================================
# Main chat area
# ============================================================
# Header row with a New Chat button (STEP 4)
header_left, header_right = st.columns([4, 1])
with header_left:
    st.title("LangGraph Chatbot")
    st.caption("Powered by LangGraph")
with header_right:
    if st.button(" New Chat", use_container_width=True):
        start_new_chat()
        st.rerun()

# LangGraph config bound to the active thread
config = {"configurable": {"thread_id": st.session_state.thread_id}}

# Render the active conversation's history
for msg in st.session_state.messages:
    with st.chat_message(msg["role"]):
        st.markdown(msg["content"])
        if msg["role"] == "assistant" and msg.get("model"):
            st.caption(f"Generated by: `{msg['model']}`")

# ---------------- Chat Input ----------------
user_input = st.chat_input("Type your message here...")

if user_input:
    # Show & store the user's message
    st.session_state.messages.append({"role": "user", "content": user_input})
    with st.chat_message("user"):
        st.markdown(user_input)

    # Stream the bot's reply from the LangGraph backend
    model_used = {"name": None}  # mutable holder filled during streaming

    def stream_chunks():
        for message_chunk, metadata in chatbot.stream(
            {"messages": [HumanMessage(content=user_input)]},
            config=config,
            stream_mode="messages",
        ):
            if model_used["name"] is None:
                model_used["name"] = extract_model_name(message_chunk, metadata)
            yield message_chunk.content

    with st.chat_message("assistant"):
        try:
            response = st.write_stream(stream_chunks())
        except Exception as e:
            response = None
            st.error(f"Something went wrong: {e}")

        if model_used["name"]:
            st.caption(f"Generated by: `{model_used['name']}`")

    if response:
        st.session_state.messages.append(
            {"role": "assistant", "content": response, "model": model_used["name"]}
        )

    # Persist this thread's history so it can be reloaded later
    st.session_state.conversations[st.session_state.thread_id] = st.session_state.messages
